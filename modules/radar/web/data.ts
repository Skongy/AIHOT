import type { RadarStatus } from "@aihot/contracts/radar";
import type { RadarEvent, RadarKind } from "../types";
export type { RadarEvent };
export const fmt = (n: number) => new Intl.NumberFormat("en-US").format(n);
export const kindLabels: Record<RadarKind, string> = { breakout: "小众黑马", comeback: "老游戏翻红", watch: "继续观察", launch: "爆火新游" };
export const statusLabels: Record<RadarStatus, string> = { suspected: "待核实", surging: "爆发中", confirmed: "已确认", cooled: "已降温" };
export const eventLabel = (e: RadarEvent) => kindLabels[e.kind];
export const launchBasis = (e: RadarEvent) => e.launch?.basis === "players" ? "在线超 2 万" : "Top 100";
export const multiplier = (e: RadarEvent) => e.kind === "launch" ? launchBasis(e) : e.baseline && e.baseline > 0 ? `${(e.peak / e.baseline).toFixed(1)}×` : e.baseline === 0 ? "从 0 增长" : "待补记录";
export const stamp = (date: string) => `${Number(date.slice(5, 7))} 月 ${Number(date.slice(8))} 日`;
export const store = (e: RadarEvent) => `https://store.steampowered.com/app/${e.appid}/`;
export const cover = (e: RadarEvent) => e.coverUrl;
